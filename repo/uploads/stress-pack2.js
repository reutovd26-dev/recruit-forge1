    const y = s._sy; s._sy += condExpr ? 175 : 95;
    const m = mkNode("modifier", 1120, y, 210, 76, label, { operation: op, value: String(value), layer });
    s.nodes.push(m); s.links.push(link(m, "out", target.n, "in", "modifies"));
